import argparse
import os

import matplotlib.pyplot as plt
import numpy as np

from Our_experiment.GA.ga_vis_common import build_agents_and_env
from Our_experiment.GA.ga_vis_common import load_json
from Our_experiment.GA.ga_vis_common import resolve_path_template
from Our_experiment.GA.ga_vis_common import rollout_once
from Our_experiment.GA.ga_vis_common import validate_traj_range


def parse_args():
    parser = argparse.ArgumentParser(
        description="GA deployment replay: aggregate UAV visit frequency heatmaps over trajectory seed range."
    )
    parser.add_argument(
        "--ga-result-json",
        type=str,
        default="Our_experiment/GA/data/ga_best_deployment_w4800_g10_i999999_t0_200.json",
        help="Path to GA deployment result JSON generated by ga_deployment_seed_search.py",
    )
    parser.add_argument("--wind-seed", type=int, default=None, help="Override wind seed from result JSON.")
    parser.add_argument("--terrain-seed", type=int, default=None, help="Override terrain seed from result JSON.")
    parser.add_argument("--infra-seed", type=int, default=None, help="Override infra seed from result JSON.")
    parser.add_argument("--traj-seed-start", type=int, default=None, help="Override traj seed start from result JSON.")
    parser.add_argument("--traj-seed-end", type=int, default=None, help="Override traj seed end from result JSON.")
    parser.add_argument(
        "--heatmap-path",
        type=str,
        default=(
            "Our_experiment/GA/data/"
            "ga_visit_frequency_w{wind_seed}_g{terrain_seed}_i{infra_seed}_t{start}_{end}.png"
        ),
        help="Output visit frequency heatmap path.",
    )
    parser.add_argument(
        "--report-path",
        type=str,
        default=(
            "Our_experiment/GA/data/"
            "ga_visit_frequency_w{wind_seed}_g{terrain_seed}_i{infra_seed}_t{start}_{end}.md"
        ),
        help="Output commentary report path.",
    )
    return parser.parse_args()


def top_k_cells(freq_map, k=5):
    flat_idx = np.argsort(freq_map.ravel())[::-1][:k]
    w = freq_map.shape[1]
    result = []
    for idx in flat_idx:
        x = int(idx // w)
        y = int(idx % w)
        result.append((x, y, float(freq_map[x, y])))
    return result


def generate_commentary(
    freq_maps_by_uav,
    uncertainty_list,
    deployment_positions,
    deployment_destinations,
    wind_seed,
    terrain_seed,
    infra_seed,
    traj_seed_start,
    traj_seed_end,
):
    lines = []
    lines.append("# GA UAV Visit Frequency Commentary")
    lines.append("")
    lines.append(f"- Wind seed: `{wind_seed}`")
    lines.append(f"- Terrain seed: `{terrain_seed}`")
    lines.append(f"- Infra seed: `{infra_seed}`")
    lines.append(f"- Trajectory seed range: `{traj_seed_start}`-`{traj_seed_end}`")
    lines.append(f"- Deployment (UAV 0..N-1): `{deployment_positions}`")
    lines.append(f"- Destination (UAV 0..N-1): `{deployment_destinations}`")
    avg_unc = float(np.mean(uncertainty_list)) if uncertainty_list else float("nan")
    lines.append(f"- Mean Average uncertainty: `{avg_unc:.6f}`")
    lines.append("")
    lines.append("## Top-5 Hotspots by UAV (Frequency)")
    lines.append("")
    for i in range(freq_maps_by_uav.shape[0]):
        lines.append(f"### UAV {i}")
        for x, y, v in top_k_cells(freq_maps_by_uav[i], k=5):
            lines.append(f"- cell ({x}, {y}): frequency `{v:.6f}`")
        lines.append("")
    return "\n".join(lines) + "\n"


def save_visit_frequency_heatmap(
    freq_maps_by_uav,
    output_path,
    wind_seed,
    terrain_seed,
    infra_seed,
    gbs_position,
    haps_position,
    grid_cell_size_m,
):
    n_uav = freq_maps_by_uav.shape[0]
    cols = 2 if n_uav > 1 else 1
    rows = int(np.ceil(n_uav / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(14, 12))
    axes = np.array(axes).reshape(-1)

    title_fs = 24
    axis_label_fs = 20
    tick_fs = 16
    suptitle_fs = 24
    cbar_label_fs = 20
    cbar_tick_fs = 16

    vmin = float(np.min(freq_maps_by_uav))
    vmax = float(np.max(freq_maps_by_uav))
    mappable = None
    for uav_idx in range(n_uav):
        ax = axes[uav_idx]
        mappable = ax.imshow(
            freq_maps_by_uav[uav_idx].T,
            cmap="viridis",
            origin="lower",
            interpolation="nearest",
            vmin=vmin,
            vmax=vmax,
        )
        ax.set_title(f"UAV {uav_idx}", fontsize=title_fs)
        ax.set_xlabel("Grid X", fontsize=axis_label_fs)
        ax.set_ylabel("Grid Y", fontsize=axis_label_fs)
        ax.tick_params(axis="both", labelsize=tick_fs)
        ax.scatter(gbs_position[0], gbs_position[1], marker="X", s=90, c="cyan", edgecolors="black", linewidths=1.0, label="GBS")
        ax.scatter(haps_position[0], haps_position[1], marker="^", s=90, c="lime", edgecolors="black", linewidths=1.0, label="HAPS")
        if uav_idx == 0:
            ax.legend(loc="upper right", fontsize=10, framealpha=0.9)

    for i in range(n_uav, len(axes)):
        axes[i].axis("off")

    cbar_ax = fig.add_axes([0.92, 0.13, 0.024, 0.74])
    cbar = fig.colorbar(mappable, cax=cbar_ax)
    cbar.set_label("Visit Frequency", fontsize=cbar_label_fs, labelpad=14)
    cbar.ax.tick_params(labelsize=cbar_tick_fs)

    title_line_1 = "GA UAV Visit Frequency by UAV"
    title_line_2 = f"w={wind_seed}, g={terrain_seed}, i={infra_seed}, cell={grid_cell_size_m:.0f}m"
    fig.suptitle(f"{title_line_1}\n{title_line_2}", fontsize=suptitle_fs, x=0.52, y=0.985)
    plt.tight_layout(rect=[0.0, 0.0, 0.90, 0.92])
    plt.savefig(output_path, dpi=220, bbox_inches="tight", pad_inches=0.1)
    plt.close()


def main():
    args = parse_args()
    ga_result = load_json(args.ga_result_json)
    result_seeds = ga_result["seeds"]

    wind_seed = int(args.wind_seed) if args.wind_seed is not None else int(result_seeds["wind_seed"])
    terrain_seed = int(args.terrain_seed) if args.terrain_seed is not None else int(result_seeds["terrain_seed"])
    infra_seed = int(args.infra_seed) if args.infra_seed is not None else int(result_seeds["infra_seed"])
    traj_seed_start = int(args.traj_seed_start) if args.traj_seed_start is not None else int(result_seeds["traj_seed_start"])
    traj_seed_end = int(args.traj_seed_end) if args.traj_seed_end is not None else int(result_seeds["traj_seed_end"])
    validate_traj_range(traj_seed_start, traj_seed_end)

    best_data = ga_result["best"]
    deployment_positions = [tuple(p) for p in best_data["deployment_positions"]]
    deployment_destinations = [tuple(p) for p in best_data.get("deployment_destinations", best_data.get("end_positions", []))]
    num_uav = len(deployment_positions)
    if len(deployment_destinations) != num_uav:
        deployment_destinations = deployment_positions.copy()

    env, agent, offload_agent = build_agents_and_env(num_uav=num_uav)
    env.reset(
        seed=0,
        positions=deployment_positions,
        destinations=deployment_destinations,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
    )
    gbs_position = np.array(env.gbs_position, dtype=np.float64).copy()
    haps_position = np.array(env.haps_position, dtype=np.float64).copy()
    grid_cell_size_m = float(getattr(env, "grid_cell_size_m", env.X / env.Lx))

    visit_sum_by_uav = None
    uncertainty_list = []
    for traj_seed in range(traj_seed_start, traj_seed_end + 1):
        stats = rollout_once(
            env=env,
            agent=agent,
            offload_agent=offload_agent,
            deployment_positions=deployment_positions,
            deployment_destinations=deployment_destinations,
            wind_seed=wind_seed,
            terrain_seed=terrain_seed,
            infra_seed=infra_seed,
            traj_seed=traj_seed,
        )
        visit_count_by_uav = stats["visit_count_by_uav"].astype(np.float64)
        if visit_sum_by_uav is None:
            visit_sum_by_uav = np.zeros_like(visit_count_by_uav, dtype=np.float64)
        visit_sum_by_uav += visit_count_by_uav
        uncertainty_list.append(float(stats["avg_uncertainty"]))

    if visit_sum_by_uav is None:
        raise RuntimeError("No rollout statistics were produced.")

    freq_maps_by_uav = np.zeros_like(visit_sum_by_uav, dtype=np.float64)
    for i in range(freq_maps_by_uav.shape[0]):
        total = float(np.sum(visit_sum_by_uav[i]))
        if total > 0:
            freq_maps_by_uav[i] = visit_sum_by_uav[i] / total

    heatmap_path = resolve_path_template(
        args.heatmap_path,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
        start=traj_seed_start,
        end=traj_seed_end,
    )
    report_path = resolve_path_template(
        args.report_path,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
        start=traj_seed_start,
        end=traj_seed_end,
    )
    os.makedirs(os.path.dirname(heatmap_path), exist_ok=True)
    os.makedirs(os.path.dirname(report_path), exist_ok=True)

    save_visit_frequency_heatmap(
        freq_maps_by_uav=freq_maps_by_uav,
        output_path=heatmap_path,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
        gbs_position=gbs_position,
        haps_position=haps_position,
        grid_cell_size_m=grid_cell_size_m,
    )
    commentary = generate_commentary(
        freq_maps_by_uav=freq_maps_by_uav,
        uncertainty_list=uncertainty_list,
        deployment_positions=deployment_positions,
        deployment_destinations=deployment_destinations,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
        traj_seed_start=traj_seed_start,
        traj_seed_end=traj_seed_end,
    )
    with open(report_path, "w", encoding="utf-8") as f:
        f.write(commentary)

    mean_unc = float(np.mean(uncertainty_list)) if uncertainty_list else float("nan")
    print("-" * 60)
    print("GA visit frequency analysis done.")
    print(f"GA result JSON: {args.ga_result_json}")
    print(f"Seeds: wind={wind_seed}, terrain={terrain_seed}, infra={infra_seed}")
    print(f"Trajectory seed range: {traj_seed_start}-{traj_seed_end}")
    print(f"Deployment positions: {deployment_positions}")
    print(f"Deployment destinations: {deployment_destinations}")
    print(f"Mean Average uncertainty: {mean_unc:.6f}")
    print(f"Visit frequency heatmap: {heatmap_path}")
    print(f"Report: {report_path}")


if __name__ == "__main__":
    main()
