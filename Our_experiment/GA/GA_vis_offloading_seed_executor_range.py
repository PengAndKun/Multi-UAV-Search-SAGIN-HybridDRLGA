def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "GA deployment replay for offloading heatmaps. "
            "Supports ga_deployment_seed_search_2 random-seed result format."
        )
    )
    parser.add_argument(
        "--ga-result-json",
        type=str,
        default="Our_experiment/GA/data/ga_best_deployment_random10_w4800_g10_i999999_pool0_200.json",
        help="Path to GA deployment result JSON generated by ga_deployment_seed_search_2.py",
    )
    parser.add_argument("--wind-seed", type=int, default=None, help="Override wind seed from result JSON.")
    parser.add_argument("--terrain-seed", type=int, default=None, help="Override terrain seed from result JSON.")
    parser.add_argument("--infra-seed", type=int, default=None, help="Override infra seed from result JSON.")
    parser.add_argument(
        "--seed-source",
        type=str,
        default="auto",
        choices=["auto", "best-iteration", "all-iterations", "range"],
        help=(
            "Trajectory seed source. auto: random mode -> best-iteration, otherwise -> range; "
            "best-iteration: use best.best_iteration_seed_set; "
            "all-iterations: flatten ga.iteration_sampled_traj_seeds; "
            "range: use traj-seed-start/end."
        ),
    )
    parser.add_argument(
        "--traj-seed-list",
        type=str,
        default=None,
        help="Manual seed list, comma-separated (e.g. 1,5,9). If set, it overrides seed-source.",
    )
    parser.add_argument("--traj-seed-start", type=int, default=None, help="Override traj seed start.")
    parser.add_argument("--traj-seed-end", type=int, default=None, help="Override traj seed end.")
    parser.add_argument(
        "--offload-metric",
        type=str,
        default="count",
        choices=["count", "frequency"],
        help="Aggregation metric for offloading heatmaps.",
    )
    parser.add_argument(
        "--heatmap-path",
        type=str,
        default=(
            "Our_experiment/GA/data/"
            "ga_offloading_frequency_w{wind_seed}_g{terrain_seed}_i{infra_seed}_{seed_tag}.png"
        ),
        help="Output offloading heatmap path.",
    )
    parser.add_argument(
        "--report-path",
        type=str,
        default=(
            "Our_experiment/GA/data/"
            "ga_offloading_frequency_w{wind_seed}_g{terrain_seed}_i{infra_seed}_{seed_tag}.md"
        ),
        help="Output commentary report path.",
    )
    parser.add_argument(
        "--terrain-map-path",
        type=str,
        default="Our_experiment/GA/data/ga_terrain_difficulty_w{wind_seed}_g{terrain_seed}_i{infra_seed}.png",
        help="Output terrain map path.",
    )
    parser.add_argument(
        "--wind-map-path",
        type=str,
        default="Our_experiment/GA/data/ga_wind_field_w{wind_seed}_g{terrain_seed}_i{infra_seed}.png",
        help="Output wind field map path.",
    )
    return parser.parse_args()


def parse_seed_list(seed_list_text):
    if seed_list_text is None:
        return None
    parts = [p.strip() for p in seed_list_text.split(",") if p.strip()]
    if not parts:
        raise ValueError("traj-seed-list is empty.")
    return [int(p) for p in parts]


def summarize_seed_list(traj_seeds, limit=25):
    if len(traj_seeds) <= limit:
        return str(traj_seeds)
    head = traj_seeds[:limit]
    return f"{head} ... (total {len(traj_seeds)})"


def select_traj_seeds(ga_result, args):
    manual_list = parse_seed_list(args.traj_seed_list)
    if manual_list is not None:
        return manual_list, "manual-list", f"list{len(manual_list)}"

    result_seeds = ga_result.get("seeds", {})
    source = args.seed_source
    if source == "auto":
        source = "best-iteration" if result_seeds.get("traj_seed_mode") == "random_per_iteration" else "range"

    if source == "best-iteration":
        best_set = ga_result.get("best", {}).get("best_iteration_seed_set", [])
        if len(best_set) > 0:
            traj_seeds = [int(s) for s in best_set]
            return traj_seeds, "best-iteration", f"bestiter{len(traj_seeds)}"
        source = "range"

    if source == "all-iterations":
        all_sets = ga_result.get("ga", {}).get("iteration_sampled_traj_seeds", [])
        traj_seeds = [int(s) for seed_set in all_sets for s in seed_set]
        if len(traj_seeds) > 0:
            return traj_seeds, "all-iterations", f"alliter{len(traj_seeds)}"
        source = "range"

    traj_seed_start = int(args.traj_seed_start) if args.traj_seed_start is not None else int(result_seeds["traj_seed_start"])
    traj_seed_end = int(args.traj_seed_end) if args.traj_seed_end is not None else int(result_seeds["traj_seed_end"])
    validate_traj_range(traj_seed_start, traj_seed_end)
    traj_seeds = list(range(traj_seed_start, traj_seed_end + 1))
    return traj_seeds, f"range({traj_seed_start}-{traj_seed_end})", f"range{traj_seed_start}_{traj_seed_end}"


def top_k_cells(freq_map, k=5):
    flat_idx = np.argsort(freq_map.ravel())[::-1][:k]
    w = freq_map.shape[1]
    result = []
    for idx in flat_idx:
        x = int(idx // w)
        y = int(idx % w)
        result.append((x, y, float(freq_map[x, y])))
    return result


def generate_commentary(
    freq_maps_by_device,
    deployment_positions,
    deployment_destinations,
    wind_seed,
    terrain_seed,
    infra_seed,
    traj_seeds,
    traj_seed_source_desc,
    mean_uncertainty,
    metric,
):
    metric_name = "Count" if metric == "count" else "Frequency"
    device_labels = ["BS", "HAPS", "LEO", "CE"]
    lines = []
    lines.append("# GA Offloading Heatmap Commentary")
    lines.append("")
    lines.append(f"- Wind seed: `{wind_seed}`")
    lines.append(f"- Terrain seed: `{terrain_seed}`")
    lines.append(f"- Infra seed: `{infra_seed}`")
    lines.append(f"- Trajectory seed source: `{traj_seed_source_desc}`")
    lines.append(f"- Trajectory seeds used ({len(traj_seeds)}): `{summarize_seed_list(traj_seeds)}`")
    lines.append(f"- Deployment (UAV 0..N-1): `{deployment_positions}`")
    lines.append(f"- Destination (UAV 0..N-1): `{deployment_destinations}`")
    lines.append(f"- Mean Average uncertainty: `{mean_uncertainty:.6f}`")
    lines.append("")
    lines.append(f"## Top-5 Hotspots by Device ({metric_name})")
    lines.append("")
    for i, dev in enumerate(device_labels):
        lines.append(f"### {dev}")
        for x, y, v in top_k_cells(freq_maps_by_device[i], k=5):
            if metric == "count":
                lines.append(f"- cell ({x}, {y}): count `{int(round(v))}`")
            else:
                lines.append(f"- cell ({x}, {y}): frequency `{v:.6f}`")
        lines.append("")
    return "\n".join(lines) + "\n"


def save_offloading_frequency_heatmap(
    freq_maps_by_device,
    output_path,
    wind_seed,
    terrain_seed,
    infra_seed,
    gbs_position,
    haps_position,
    grid_cell_size_m,
    metric,
    avg_uncertainty,
):
    title_fs = 24
    axis_label_fs = 20
    tick_fs = 16
    suptitle_fs = 24
    cbar_label_fs = 20
    cbar_tick_fs = 16

    device_labels = ["BS", "HAPS", "LEO", "CE"]
    fig, axes = plt.subplots(2, 2, figsize=(14, 12))
    axes = axes.flatten()

    vmin = float(np.min(freq_maps_by_device))
    vmax = float(np.max(freq_maps_by_device))

    mappable = None
    for i, dev in enumerate(device_labels):
        ax = axes[i]
        mappable = ax.imshow(
            freq_maps_by_device[i].T,
            cmap="hot",
            origin="lower",
            interpolation="nearest",
            vmin=vmin,
            vmax=vmax,
        )
        ax.set_title(dev, fontsize=title_fs)
        ax.set_xlabel("Grid X", fontsize=axis_label_fs)
        ax.set_ylabel("Grid Y", fontsize=axis_label_fs)
        ax.tick_params(axis="both", labelsize=tick_fs)
        ax.scatter(gbs_position[0], gbs_position[1], marker="X", s=110, c="cyan", edgecolors="black", linewidths=1.0, label="GBS")
        ax.scatter(haps_position[0], haps_position[1], marker="^", s=110, c="lime", edgecolors="black", linewidths=1.0, label="HAPS")
        if i == 0:
            ax.legend(loc="upper right", fontsize=12, framealpha=0.9)

    cbar_ax = fig.add_axes([0.92, 0.13, 0.024, 0.74])
    cbar = fig.colorbar(mappable, cax=cbar_ax)
    cbar_label = "Offloading Count" if metric == "count" else "Offloading Frequency"
    cbar.set_label(cbar_label, fontsize=cbar_label_fs, labelpad=14)
    cbar.ax.tick_params(labelsize=cbar_tick_fs)

    metric_text = "Count" if metric == "count" else "Frequency"
    title_line_1 = f"GA Offloading {metric_text} by Device"
    title_line_2 = (
        f"w={wind_seed}, g={terrain_seed}, i={infra_seed}, "
        f"cell={grid_cell_size_m:.0f}m, avg_unc={avg_uncertainty:.6f}"
    )
    fig.suptitle(f"{title_line_1}\n{title_line_2}", fontsize=suptitle_fs, x=0.52, y=0.985)
    plt.tight_layout(rect=[0.0, 0.0, 0.90, 0.92])
    plt.savefig(output_path, dpi=220, bbox_inches="tight", pad_inches=0.1)
    plt.close()


