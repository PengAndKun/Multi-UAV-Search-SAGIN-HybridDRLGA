def save_wind_field_map(wind_u, wind_v, output_path, wind_seed, terrain_seed, infra_seed, gbs_position, haps_position, grid_cell_size_m):
    title_fs = 24
    axis_label_fs = 20
    tick_fs = 16
    suptitle_fs = 24
    cbar_label_fs = 20
    cbar_tick_fs = 16

    speed = np.sqrt(wind_u ** 2 + wind_v ** 2)
    fig, ax = plt.subplots(1, 1, figsize=(10, 8))
    mappable = ax.imshow(
        speed.T,
        cmap="Blues",
        origin="lower",
        interpolation="nearest",
    )

    grid_x = np.arange(wind_u.shape[0])
    grid_y = np.arange(wind_u.shape[1])
    x_mesh, y_mesh = np.meshgrid(grid_x, grid_y, indexing="xy")
    ax.quiver(
        x_mesh,
        y_mesh,
        wind_u.T,
        wind_v.T,
        color="black",
        scale=80,
        width=0.0025,
        alpha=0.6,
    )

    ax.set_title("Wind Field", fontsize=title_fs)
    ax.set_xlabel("Grid X", fontsize=axis_label_fs)
    ax.set_ylabel("Grid Y", fontsize=axis_label_fs)
    ax.tick_params(axis="both", labelsize=tick_fs)
    ax.scatter(gbs_position[0], gbs_position[1], marker="X", s=140, c="cyan", edgecolors="black", linewidths=1.0, label="GBS")
    ax.scatter(haps_position[0], haps_position[1], marker="^", s=140, c="lime", edgecolors="black", linewidths=1.0, label="HAPS")
    ax.legend(loc="upper right", fontsize=12, framealpha=0.9)

    cbar_ax = fig.add_axes([0.92, 0.13, 0.024, 0.74])
    cbar = fig.colorbar(mappable, cax=cbar_ax)
    cbar.set_label("Wind Speed", fontsize=cbar_label_fs, labelpad=14)
    cbar.ax.tick_params(labelsize=cbar_tick_fs)

    title_line_1 = "GA Wind Field Map"
    title_line_2 = f"w={wind_seed}, g={terrain_seed}, i={infra_seed}, cell={grid_cell_size_m:.0f}m"
    fig.suptitle(f"{title_line_1}\n{title_line_2}", fontsize=suptitle_fs, x=0.52, y=0.985)
    plt.tight_layout(rect=[0.0, 0.0, 0.90, 0.92])
    plt.savefig(output_path, dpi=220, bbox_inches="tight", pad_inches=0.1)
    plt.close()


def main():
    args = parse_args()
    ga_result = load_json(args.ga_result_json)
    result_seeds = ga_result["seeds"]

    wind_seed = int(args.wind_seed) if args.wind_seed is not None else int(result_seeds["wind_seed"])
    terrain_seed = int(args.terrain_seed) if args.terrain_seed is not None else int(result_seeds["terrain_seed"])
    infra_seed = int(args.infra_seed) if args.infra_seed is not None else int(result_seeds["infra_seed"])
    traj_seeds, traj_seed_source_desc, seed_tag = select_traj_seeds(ga_result, args)
    if len(traj_seeds) == 0:
        raise RuntimeError("No trajectory seeds selected.")

    best_data = ga_result["best"]
    deployment_positions = [tuple(p) for p in best_data["deployment_positions"]]
    deployment_destinations = [tuple(p) for p in best_data.get("deployment_destinations", best_data.get("end_positions", []))]
    num_uav = len(deployment_positions)
    if len(deployment_destinations) != num_uav:
        deployment_destinations = deployment_positions.copy()

    env, agent, offload_agent = build_agents_and_env(num_uav=num_uav)
    env.reset(
        seed=0,
        positions=deployment_positions,
        destinations=deployment_destinations,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
    )
    gbs_position = np.array(env.gbs_position, dtype=np.float64).copy()
    haps_position = np.array(env.haps_position, dtype=np.float64).copy()
    grid_cell_size_m = float(getattr(env, "grid_cell_size_m", env.X / env.Lx))

    offload_sum_by_device = None
    uncertainty_list = []
    for traj_seed in traj_seeds:
        stats = rollout_once(
            env=env,
            agent=agent,
            offload_agent=offload_agent,
            deployment_positions=deployment_positions,
            deployment_destinations=deployment_destinations,
            wind_seed=wind_seed,
            terrain_seed=terrain_seed,
            infra_seed=infra_seed,
            traj_seed=int(traj_seed),
        )
        heatmaps_devices = stats["offload_heatmaps_by_target"][1:5].astype(np.float64)  # BS/HAPS/LEO/CE
        if offload_sum_by_device is None:
            offload_sum_by_device = np.zeros_like(heatmaps_devices, dtype=np.float64)
        offload_sum_by_device += heatmaps_devices
        uncertainty_list.append(float(stats["avg_uncertainty"]))

    if offload_sum_by_device is None:
        raise RuntimeError("No rollout statistics were produced.")

    if args.offload_metric == "count":
        freq_maps_by_device = offload_sum_by_device.copy()
    else:
        freq_maps_by_device = np.zeros_like(offload_sum_by_device, dtype=np.float64)
        for i in range(offload_sum_by_device.shape[0]):
            total_i = float(np.sum(offload_sum_by_device[i]))
            if total_i > 0:
                freq_maps_by_device[i] = offload_sum_by_device[i] / total_i

    seed_start = int(min(traj_seeds))
    seed_end = int(max(traj_seeds))
    heatmap_path = resolve_path_template(
        args.heatmap_path,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
        start=seed_start,
        end=seed_end,
        seed_tag=seed_tag,
    )
    report_path = resolve_path_template(
        args.report_path,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
        start=seed_start,
        end=seed_end,
        seed_tag=seed_tag,
    )
    terrain_map_path = resolve_path_template(
        args.terrain_map_path,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
    )
    wind_map_path = resolve_path_template(
        args.wind_map_path,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
    )
    os.makedirs(os.path.dirname(heatmap_path), exist_ok=True)
    os.makedirs(os.path.dirname(report_path), exist_ok=True)
    os.makedirs(os.path.dirname(terrain_map_path), exist_ok=True)
    os.makedirs(os.path.dirname(wind_map_path), exist_ok=True)

    save_terrain_difficulty_map(
        env.task_matrix.astype(np.float64),
        terrain_map_path,
        wind_seed,
        terrain_seed,
        infra_seed,
        gbs_position,
        haps_position,
        grid_cell_size_m,
    )
    save_wind_field_map(
        env.wind_u.astype(np.float64),
        env.wind_v.astype(np.float64),
        wind_map_path,
        wind_seed,
        terrain_seed,
        infra_seed,
        gbs_position,
        haps_position,
        grid_cell_size_m,
    )
    mean_unc = float(np.mean(uncertainty_list)) if uncertainty_list else float("nan")
    std_unc = float(np.std(uncertainty_list)) if uncertainty_list else float("nan")
    save_offloading_frequency_heatmap(
        freq_maps_by_device,
        heatmap_path,
        wind_seed,
        terrain_seed,
        infra_seed,
        gbs_position,
        haps_position,
        grid_cell_size_m,
        args.offload_metric,
        mean_unc,
    )
    commentary = generate_commentary(
        freq_maps_by_device=freq_maps_by_device,
        deployment_positions=deployment_positions,
        deployment_destinations=deployment_destinations,
        wind_seed=wind_seed,
        terrain_seed=terrain_seed,
        infra_seed=infra_seed,
        traj_seeds=traj_seeds,
        traj_seed_source_desc=traj_seed_source_desc,
        mean_uncertainty=mean_unc,
        metric=args.offload_metric,
    )
    with open(report_path, "w", encoding="utf-8") as f:
        f.write(commentary)

    print("-" * 60)
    print("GA offloading frequency analysis done.")
    print(f"GA result JSON: {args.ga_result_json}")
    print(f"Seeds: wind={wind_seed}, terrain={terrain_seed}, infra={infra_seed}")
    print(f"Trajectory seed source: {traj_seed_source_desc}")
    print(f"Trajectory seeds used ({len(traj_seeds)}): {summarize_seed_list(traj_seeds)}")
    print(f"Deployment positions: {deployment_positions}")
    print(f"Deployment destinations: {deployment_destinations}")
    print(f"Mean Average uncertainty: {mean_unc:.6f}")
    print(f"Std Average uncertainty: {std_unc:.6f}")
    print(f"Terrain map: {terrain_map_path}")
    print(f"Wind map: {wind_map_path}")
    print(f"Offloading heatmap: {heatmap_path}")
    print(f"Report: {report_path}")


if __name__ == "__main__":
    main()
