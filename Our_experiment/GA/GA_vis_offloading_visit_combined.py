    axis_label_fs = 20
    tick_fs = 16
    suptitle_fs = 24
    cbar_label_fs = 20
    cbar_tick_fs = 16

    speed = np.sqrt(wind_u ** 2 + wind_v ** 2)
    fig, ax = plt.subplots(1, 1, figsize=(10, 8))
    mappable = ax.imshow(
        speed.T,
        cmap="Blues",
        origin="lower",
        interpolation="nearest",
    )

